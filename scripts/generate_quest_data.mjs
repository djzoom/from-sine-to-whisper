// Builds quest/src/course-snapshot.generated.js from the course table in README.md.
//
//     node scripts/generate_quest_data.mjs
//
// The README is the single source of truth for lesson codes, titles, phases and
// folders. Re-run this whenever the course table changes (for example after
// scripts/update_readme.py), so the game's course guide never drifts from it.
//
// Output shape (what quest/src/data/worldmap.js reads):
//   title, subtitle         the README's H1 and its bold one-line summary
//   openingLessons          the first five lessons: { code, path, title }
//   foundationTracks        the four maths phases (1–4): { path, range, title }
//   phases                  every phase: { phase, icon, title, folder, range,
//                           lessons: [[code, title, path], ...] }
//   sourceFiles             the files this snapshot was built from

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "..");
const readmePath = path.join(repoRoot, "README.md");
const outputPath = path.join(repoRoot, "quest", "src", "course-snapshot.generated.js");

// "### 🔊 Phase 5 · Audio DSP  `5_audio_dsp/`  L32–L53"
const PHASE_HEADING =
  /^###\s+(\S+)\s+(Phase\s+\d+)\s+·\s+(.+?)\s+`([^`]+)`\s+(L\d+\s*[–-]\s*L\d+)\s*$/u;

// "| [L08](notebooks/1_complex_trig/L08_visual_complex.ipynb) 🎨 | Title |"
// or, for an untranslated lesson, "| L08 🎨 | Title *(coming soon — ...)* |"
const LESSON_ROW =
  /^\|\s*(?:\[(L\d+)\]\(([^)]*)\)|(L\d+))(\s*🎨)?\s*\|\s*(.+?)\s*\|\s*$/u;

function cleanTitle(value) {
  return value
    .replace(/\s*\*\(coming soon[^)]*\)[^*]*\)?\*\s*$/u, "") // untranslated marker
    .replace(/\\\|/g, "|") // escaped pipes inside table cells
    .replace(/`/g, "")
    .replace(/\*\*/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function parseReadme(text) {
  const lines = text.split(/\r?\n/);
  const title = lines.find((line) => line.startsWith("# "))?.replace(/^#\s+/, "").trim() ?? "";
  const subtitle =
    lines
      .find((line) => /^\*\*.+\*\*$/.test(line.trim()))
      ?.trim()
      .replace(/^\*\*|\*\*$/g, "") ?? "";

  const phases = [];
  let current = null;
  for (const line of lines) {
    const heading = line.match(PHASE_HEADING);
    if (heading) {
      current = {
        phase: heading[2],
        icon: heading[1],
        title: heading[3].trim(),
        folder: heading[4],
        range: heading[5].replace(/\s*[–-]\s*/, "–"),
        lessons: [],
      };
      phases.push(current);
      continue;
    }
    if (/^#{1,3}\s/.test(line)) {
      current = null; // any other heading ends the current phase table
      continue;
    }
    if (!current) continue;
    const row = line.match(LESSON_ROW);
    if (!row) continue;
    const code = row[1] ?? row[3];
    const visual = row[4] ? " 🎨" : "";
    const notebook = row[2] ?? "";
    current.lessons.push([`${code}${visual}`, cleanTitle(row[5]), notebook]);
  }
  return { title, subtitle, phases };
}

async function main() {
  const readme = await fs.readFile(readmePath, "utf8");
  const { title, subtitle, phases } = parseReadme(readme);

  const lessonCount = phases.reduce((sum, phase) => sum + phase.lessons.length, 0);
  if (phases.length === 0 || lessonCount === 0) {
    throw new Error("No course table found in README.md — has its format changed?");
  }

  const allLessons = phases.flatMap((phase) => phase.lessons);
  const openingLessons = allLessons.slice(0, 5).map(([code, lessonTitle, notebook]) => ({
    code: code.replace(/\s*🎨$/u, ""),
    path: notebook.replace(/^notebooks\//, "").replace(/\.ipynb$/, ""),
    title: lessonTitle,
  }));
  const foundationTracks = phases.slice(1, 5).map((phase) => ({
    path: phase.folder,
    range: phase.range,
    title: phase.title,
  }));

  const data = {
    title,
    subtitle,
    openingLessons,
    foundationTracks,
    phases,
    sourceFiles: ["README.md"],
  };

  const code =
    "// Generated by scripts/generate_quest_data.mjs from README.md — do not edit by hand.\n" +
    `export const courseSnapshot = ${JSON.stringify(data, null, 2)};\n\nexport default courseSnapshot;\n`;
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, code, "utf8");
  console.log(
    `wrote ${path.relative(repoRoot, outputPath)} (${phases.length} phases, ${lessonCount} lessons)`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
